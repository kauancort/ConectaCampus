test.describe.configure({ mode: 'serial' })

const api = process.env.E2E_API_URL || 'http://127.0.0.1:5077'
const password = 'Fatec!Teste2026'
const unique = `${Date.now()}-${Math.random().toString(36).slice(2, 8)}`
